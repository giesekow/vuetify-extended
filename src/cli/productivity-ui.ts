function patchRoutesIndexSource(source: string, answers: RouteAnswers) {
  const routeIdentifier = routeIdentifierForName(answers.name);
  const importLine = `import { ${routeIdentifier} } from './${answers.name}';`;
  const itemLine = `  ${routeIdentifier},`;
  let next = ensureRouteIndexMarkers(source);
  if (!next) {
    return undefined;
  }
  if (!next.includes(importLine)) {
    next = next.replace(ROUTES_IMPORT_MARKER, `${ROUTES_IMPORT_MARKER}\n${importLine}`);
  }
  if (!next.includes(itemLine)) {
    next = next.replace(ROUTES_ITEM_MARKER, `${ROUTES_ITEM_MARKER}\n${itemLine}`);
  }
  return next;
}

function ensureRouteIndexMarkers(source: string) {
  let next = source;
  if (!next.includes(ROUTES_IMPORT_MARKER)) {
    const importMatches = Array.from(next.matchAll(/^import .*$/gm));
    if (importMatches.length > 0) {
      const lastImport = importMatches[importMatches.length - 1];
      const insertAt = (lastImport.index || 0) + lastImport[0].length;
      next = `${next.slice(0, insertAt)}\n${ROUTES_IMPORT_MARKER}${next.slice(insertAt)}`;
    } else {
      next = `${ROUTES_IMPORT_MARKER}\n\n${next}`;
    }
  }

  if (!next.includes(ROUTES_ITEM_MARKER)) {
    const arrayPattern = /export const appRoutes(?:\s*:\s*AppRouteEntry\[\])?\s*=\s*\[/;
    if (!arrayPattern.test(next)) {
      return undefined;
    }
    next = next.replace(arrayPattern, (match) => `${match}\n  ${ROUTES_ITEM_MARKER}`);
  }

  return next;
}

