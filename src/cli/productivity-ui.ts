async function resolveRouteAnswers(options: CreateCommandOptions): Promise<RouteAnswers | undefined> {
  const values = options.values || {};
  const input = {
    name: values.name || options.positionals?.[0],
    title: values.title,
    path: values.path,
    page: values.page,
    target: values.target as PageTarget | undefined,
    mode: values.mode as ReportMode | undefined,
  };

  if (!options.interactive) {
    if (!input.name || !input.page) {
      options.stderr.write('[vuetify-ext] Missing required flags for create route:\n- --name\n- --page\n');
      return undefined;
    }
    const target = input.target || 'report';
    return {
      name: slugifyName(input.name),
      title: input.title || humanizeName(input.name),
      path: input.path || `/${slugifyName(input.name)}`,
      page: slugifyName(input.page),
      target,
      mode: normalizeMode(input.mode, defaultModeForTarget(target)),
    };
  }

  const rl = readline.createInterface({ input: options.stdin, output: options.stdout as NodeJS.WritableStream });
  try {
    const name = slugifyName(await promptText(rl, 'Route name/file', input.name || 'workspace-home'));
    const page = slugifyName(await promptText(rl, 'Page folder', input.page || name));
    const target = await promptChoice(rl, 'Target (report/trigger/collection/dashboard)', ['report', 'trigger', 'collection', 'dashboard'], input.target || 'report') as PageTarget;
    const title = await promptText(rl, 'Route title', input.title || humanizeName(name));
    const routePath = await promptText(rl, 'Route path', input.path || `/${name}`);
    const mode = await promptChoice(rl, 'Default mode (create/edit/display)', ['create', 'edit', 'display'], input.mode || defaultModeForTarget(target)) as ReportMode;
    return { name, title, path: routePath, page, target, mode };
  } finally {
    rl.close();
  }
}

