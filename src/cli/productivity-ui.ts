export async function runCreateRouteCommand(options: CreateCommandOptions): Promise<number> {
  const answers = await resolveRouteAnswers(options);
  if (!answers) {
    return 1;
  }

  const ext = resolveExistingPageScriptExtension(options.cwd, answers.page) || resolveProjectScriptExtension(options.cwd);
  const pageIndexFile = path.join(options.cwd, 'src/pages', answers.page, `index${ext}`);
  const factoryName = `create${toPascalCase(answers.page)}${capitalize(answers.target)}`;
  if (!verifyExpectedPageExport(pageIndexFile, factoryName)) {
    options.stderr.write(
      `[vuetify-ext] ${relativeToCwd(options.cwd, pageIndexFile)} is missing ${factoryName}.\n`,
    );
    return 1;
  }

  const routesDir = path.join(options.cwd, 'src/routes');
  const routeFile = path.join(routesDir, `${answers.name}${ext}`);
  const routesIndexFile = path.join(routesDir, `index${ext}`);
  const prepare = prepareWrites(options, [
    { file: routeFile, content: buildRouteFileSource(answers) },
  ]);
  if (prepare === 'error') {
    return 1;
  }

  const currentIndexSource = fileExists(routesIndexFile)
    ? fs.readFileSync(routesIndexFile, 'utf8')
    : buildRoutesIndexFileSource(ext);
  const nextIndexSource = patchRoutesIndexSource(currentIndexSource, answers);
  if (!nextIndexSource) {
    options.stderr.write(
      `[vuetify-ext] Could not patch ${relativeToCwd(options.cwd, routesIndexFile)} automatically.\n`,
    );
    return 1;
  }

  if (prepare === 'dry-run') {
    options.stdout.write(`- ${relativeToCwd(options.cwd, routesIndexFile)}\n`);
    return 0;
  }

  writeFiles([{ file: routeFile, content: buildRouteFileSource(answers) }]);
  fs.mkdirSync(path.dirname(routesIndexFile), { recursive: true });
  fs.writeFileSync(routesIndexFile, nextIndexSource, 'utf8');
  writeSuccess(options, 'Route scaffolding created successfully', [routeFile, routesIndexFile]);
  return 0;
}

