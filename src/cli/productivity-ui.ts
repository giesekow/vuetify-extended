export async function runCreateHeaderItemCommand(options: CreateCommandOptions): Promise<number> {
  const answers = await resolveHeaderItemAnswers(options);
  if (!answers) {
    return 1;
  }

  const ext = resolveProjectScriptExtension(options.cwd);
  const headerFile = findExistingFile(options.cwd, ['src/bootstrap/header.ts', 'src/bootstrap/header.js']) || path.join(options.cwd, 'src/bootstrap', `header${ext}`);
  if (!fileExists(headerFile)) {
    options.stderr.write('[vuetify-ext] Bootstrap header file not found. Run "vuetify-ext bootstrap app" first.\n');
    return 1;
  }

  const itemMarker = `// vuetify-ext:header-item:${answers.region}:${answers.kind}:${slugifyName(answers.text)}`;
  let source = fs.readFileSync(headerFile, 'utf8');
  if (source.includes(itemMarker)) {
    writeSuccess(options, 'Header item already present', [headerFile]);
    return 0;
  }

  source = ensureHeaderMarkers(source) || '';
  if (!source) {
    options.stderr.write(`[vuetify-ext] Could not normalize header regions in ${relativeToCwd(options.cwd, headerFile)}.\n`);
    return 1;
  }

  source = ensureVuetifyExtendedImport(source, ['$ATB', '$ENV', '$SIA', '$STB', '$USR']);
  if (answers.kind === 'action') {
    source = ensureImportLine(source, `import { Dialogs } from 'vuetify-extended';`);
  }

  const regionMarker = answers.region === 'start' ? HEADER_START_MARKER : answers.region === 'center' ? HEADER_CENTER_MARKER : HEADER_END_MARKER;
  const next = source.replace(regionMarker, `${regionMarker}\n${buildHeaderItemBlock(answers, itemMarker)}`);

  if (options.dryRun) {
    options.stdout.write(`[vuetify-ext] Dry run only. The following file would be updated:\n- ${relativeToCwd(options.cwd, headerFile)}\n`);
    return 0;
  }

  fs.writeFileSync(headerFile, next, 'utf8');
  writeSuccess(options, 'Header item added successfully', [headerFile]);
  return 0;
}

