function prepareWrites(options: CreateCommandOptions, writes: FileWrite[]): PrepareWritesResult {
  const duplicates = new Set<string>();
  const existing: string[] = [];

  for (const write of writes) {
    if (duplicates.has(write.file)) {
      continue;
    }
    duplicates.add(write.file);
    if (!options.force && fileExists(write.file)) {
      existing.push(write.file);
    }
  }

  if (existing.length > 0) {
    options.stderr.write(
      `[vuetify-ext] The following files already exist:\n- ${existing.map(file => relativeToCwd(options.cwd, file)).join('\n- ')}\n` +
        'Use --force to overwrite them.\n',
    );
    return 'error';
  }

  if (options.dryRun) {
    options.stdout.write('[vuetify-ext] Dry run only. The following files would be written:\n');
    for (const write of writes) {
      options.stdout.write(`- ${relativeToCwd(options.cwd, write.file)}\n`);
    }
    return 'dry-run';
  }

  return 'ok';
}

function writeFiles(writes: FileWrite[]) {
  for (const write of writes) {
    fs.mkdirSync(path.dirname(write.file), { recursive: true });
    fs.writeFileSync(write.file, write.content, 'utf8');
  }
}

