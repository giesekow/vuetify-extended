function resolveProjectScriptExtension(cwd: string): ScriptExt {
  const candidates = [
    path.join(cwd, 'src/main.ts'),
    path.join(cwd, 'src/menu/index.ts'),
    path.join(cwd, 'src/pages/home/index.ts'),
  ];
  if (candidates.some(fileExists)) {
    return '.ts';
  }

  const jsCandidates = [
    path.join(cwd, 'src/main.js'),
    path.join(cwd, 'src/menu/index.js'),
    path.join(cwd, 'src/pages/home/index.js'),
  ];
  if (jsCandidates.some(fileExists)) {
    return '.js';
  }

  return fileExists(path.join(cwd, 'tsconfig.json')) ? '.ts' : '.js';
}

function resolveMenuFile(cwd: string, ext: ScriptExt, override?: string): string | undefined {
  if (override) {
    return path.isAbsolute(override) ? override : path.join(cwd, override);
  }

  const candidates = [
    path.join(cwd, 'src/menu/index.ts'),
    path.join(cwd, 'src/menu/index.js'),
    path.join(cwd, `src/menu/index${ext}`),
  ];

  return candidates.find(fileExists);
}

function resolveParentMenuFile(cwd: string, ext: ScriptExt, parent?: string, override?: string): string | undefined {
  if (override) {
    return resolveMenuFile(cwd, ext, override);
  }

  if (!parent || parent === 'main') {
    return resolveMenuFile(cwd, ext);
  }

  const parentName = slugifyName(parent);
  const candidates = [
    path.join(cwd, 'src/menu', `${parentName}.ts`),
    path.join(cwd, 'src/menu', `${parentName}.js`),
    path.join(cwd, 'src/menu', `${parentName}${ext}`),
  ];

  return candidates.find(fileExists);
}

