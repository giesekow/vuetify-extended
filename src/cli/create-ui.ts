export async function runCreateCollectionCommand(options: CreateCommandOptions): Promise<number> {
  const ext = resolveProjectScriptExtension(options.cwd);
  const answers = await resolveCollectionAnswers(options);
  if (!answers) {
    return 1;
  }

  const pageDir = path.join(options.cwd, 'src/pages', answers.name);
  const pascalName = toPascalCase(answers.name);
  const expectedReportFactory = `create${pascalName}Report`;
  const expectedTriggerFactory = `create${pascalName}Trigger`;

  if (!answers.withReport && !verifyExpectedPageExport(path.join(pageDir, `report${ext}`), expectedReportFactory)) {
    options.stderr.write(
      `[vuetify-ext] ${relativeToCwd(options.cwd, path.join(pageDir, `report${ext}`))} is missing the expected export ${expectedReportFactory}.\n` +
        'Either allow the command to scaffold the report or create it first using the standard factory name.\n',
    );
    return 1;
  }

  if (!answers.withTrigger && !verifyExpectedPageExport(path.join(pageDir, `trigger${ext}`), expectedTriggerFactory)) {
    options.stderr.write(
      `[vuetify-ext] ${relativeToCwd(options.cwd, path.join(pageDir, `trigger${ext}`))} is missing the expected export ${expectedTriggerFactory}.\n` +
        'Either allow the command to scaffold the trigger or create it first using the standard factory name.\n',
    );
    return 1;
  }

  const writes: FileWrite[] = [];

  if (answers.withReport) {
    writes.push(...buildReportWrites(pageDir, ext, {
      name: answers.name,
      title: answers.title,
      objectType: answers.objectType,
      mode: answers.mode,
      forms: 1,
    }, pascalName));
  }

  if (answers.withTrigger) {
    writes.push(...buildTriggerWrites(pageDir, ext, answers, pascalName));
  }

  writes.push(...buildCollectionWrites(pageDir, ext, answers, pascalName));

  const ok = prepareWrites(options, writes);
  if (ok === 'error') {
    return 1;
  }
  if (ok === 'dry-run') {
    options.stdout.write(`- ${relativeToCwd(options.cwd, path.join(pageDir, `index${ext}`))}\n`);
    return 0;
  }

  writeFiles(writes);

  const exports = [
    `export { create${pascalName}Collection } from './collection';`,
  ];
  if (answers.withReport || fileExists(path.join(pageDir, `report${ext}`))) {
    exports.unshift(`export { create${pascalName}Report } from './report';`);
  }
  if (answers.withTrigger || fileExists(path.join(pageDir, `trigger${ext}`))) {
    exports.unshift(`export { create${pascalName}Trigger } from './trigger';`);
  }
  if (answers.withReport || fileExists(path.join(pageDir, `form${ext}`))) {
    exports.unshift(`export { create${pascalName}Form } from './form';`);
  }
  ensureIndexExports(pageDir, ext, exports);

  writeSuccess(options, 'Collection scaffolding created successfully', [
    ...writes.map((entry) => entry.file),
    path.join(pageDir, `index${ext}`),
  ]);
  options.stdout.write(
    '\nNext steps:\n' +
      `1. Review src/pages/${answers.name}/collection${ext} and connect it to your real report/trigger behavior.\n` +
      `2. Replace the starter trigger dataset with live loading if needed.\n` +
      `3. Run "vuetify-ext create menu-item --page ${answers.name} --target collection" when you want it in the main menu.\n`,
  );

  return 0;
}

export async function runCreateMenuItemCommand(options: CreateCommandOptions): Promise<number> {
  const answers = await resolveMenuItemAnswers(options);
  if (!answers) {
    return 1;
  }
  const ext = resolveExistingPageScriptExtension(options.cwd, answers.page) || resolveProjectScriptExtension(options.cwd);

  const pageIndexFile = path.join(options.cwd, 'src/pages', answers.page, `index${ext}`);
  const expectedFactoryName = `create${toPascalCase(answers.page)}${capitalize(answers.target)}`;
  if (!verifyExpectedPageExport(pageIndexFile, expectedFactoryName)) {
    options.stderr.write(
      `[vuetify-ext] ${relativeToCwd(options.cwd, pageIndexFile)} is missing the expected export ${expectedFactoryName}.\n` +
        `Create the page first or export ${expectedFactoryName} from the page index before adding the menu item.\n`,
    );
    return 1;
  }

  const menuFile = resolveMenuFile(options.cwd, ext, answers.menuFile);
  if (!menuFile) {
    options.stderr.write(
      '[vuetify-ext] Could not locate src/menu/index.ts or src/menu/index.js.\n' +
        'Run "vuetify-ext bootstrap app" first or pass --menu-file.\n',
    );
    return 1;
  }

  if (!fileExists(menuFile)) {
    options.stderr.write(`[vuetify-ext] Menu file not found: ${relativeToCwd(options.cwd, menuFile)}\n`);
    return 1;
  }

  const source = fs.readFileSync(menuFile, 'utf8');
  const patched = patchMenuFile(source, answers);
  if (!patched) {
    options.stderr.write(
      `[vuetify-ext] Could not patch ${relativeToCwd(options.cwd, menuFile)} automatically.\n` +
        'Make sure the file contains createMainMenu() with a children: async () => [ ... ] block.\n',
    );
    return 1;
  }

  if (options.dryRun) {
    options.stdout.write('[vuetify-ext] Dry run only. The following file would be updated:\n');
    options.stdout.write(`- ${relativeToCwd(options.cwd, menuFile)}\n`);
    return 0;
  }

  fs.writeFileSync(menuFile, patched, 'utf8');
  writeSuccess(options, 'Menu item added successfully', [menuFile]);
  options.stdout.write(
    '\nNext steps:\n' +
      `1. Open ${relativeToCwd(options.cwd, menuFile)} and confirm the inserted import and menu item labels.\n` +
      '2. Run the app and verify the new menu card opens the expected page.\n',
  );

  return 0;
}

export async function runCreateSubMenuCommand(options: CreateCommandOptions): Promise<number> {
  const initialExt = resolveProjectScriptExtension(options.cwd);
  const answers = await resolveSubMenuAnswers(options);
  if (!answers) {
    return 1;
  }

  const parentMenuFile = resolveParentMenuFile(options.cwd, initialExt, answers.parent, answers.menuFile);
  if (!parentMenuFile) {
    options.stderr.write(
      '[vuetify-ext] Could not locate the parent menu file.\n' +
        'Run "vuetify-ext bootstrap app" first, pass --parent <menu-name>, or use --menu-file.\n',
    );
    return 1;
  }

  if (!fileExists(parentMenuFile)) {
    options.stderr.write(`[vuetify-ext] Parent menu file not found: ${relativeToCwd(options.cwd, parentMenuFile)}\n`);
    return 1;
  }

  const ext = normalizeScriptExt(path.extname(parentMenuFile)) || initialExt;
  const subMenuFile = path.join(options.cwd, 'src/menu', `${answers.name}${ext}`);
  if (path.resolve(parentMenuFile) === path.resolve(subMenuFile)) {
    options.stderr.write('[vuetify-ext] The submenu file cannot also be the parent menu file.\n');
    return 1;
  }

  const pascalName = toPascalCase(answers.name);
  const writes: FileWrite[] = [
    {
      file: subMenuFile,
      content: buildSubMenuFileSource(answers, pascalName),
    },
  ];

  const ok = prepareWrites(options, writes);
  if (ok === 'error') {
    return 1;
  }

  const parentSource = fs.readFileSync(parentMenuFile, 'utf8');
  const patchedParentSource = patchMenuFileWithSubMenu(parentSource, parentMenuFile, subMenuFile, answers, pascalName);
  if (!patchedParentSource) {
    options.stderr.write(
      `[vuetify-ext] Could not patch ${relativeToCwd(options.cwd, parentMenuFile)} automatically.\n` +
        'Make sure the file contains create...Menu() with a children: async () => [ ... ] block.\n',
    );
    return 1;
  }

  if (options.dryRun) {
    options.stdout.write('[vuetify-ext] Dry run only. The following files would be written or updated:\n');
    options.stdout.write(`- ${relativeToCwd(options.cwd, subMenuFile)}\n`);
    options.stdout.write(`- ${relativeToCwd(options.cwd, parentMenuFile)}\n`);
    return 0;
  }

  writeFiles(writes);
  fs.writeFileSync(parentMenuFile, patchedParentSource, 'utf8');

  writeSuccess(options, 'Sub-menu created successfully', [
    subMenuFile,
    parentMenuFile,
  ]);
  options.stdout.write(
    '\nNext steps:\n' +
      `1. Add child items to ${relativeToCwd(options.cwd, subMenuFile)} with "vuetify-ext create menu-item --menu-file ${relativeToCwd(options.cwd, subMenuFile)}".\n` +
      `2. Review ${relativeToCwd(options.cwd, parentMenuFile)} and confirm the inserted parent menu card styling.\n` +
      '3. Run the app and verify the new card opens the nested menu.\n',
  );

  return 0;
}

export async function runCreateFormCommand(options: CreateCommandOptions): Promise<number> {
  const initialExt = resolveProjectScriptExtension(options.cwd);
  const answers = await resolveFormStepAnswers(options, initialExt);
  if (!answers) {
    return 1;
  }
  const ext = resolveExistingPageScriptExtension(options.cwd, answers.page) || initialExt;

  const pageDir = path.join(options.cwd, 'src/pages', answers.page);
  const pascalName = toPascalCase(answers.page);
  const reportFile = path.join(pageDir, `report${ext}`);
  const indexFile = path.join(pageDir, `index${ext}`);
  const formFile = path.join(pageDir, formFileNameForStep(answers.step, ext));
  const formFunctionName = formFunctionNameForStep(pascalName, answers.step);
  const baseFormFunctionName = formFunctionNameForStep(pascalName, 1);
  const reportFunctionName = `create${pascalName}Report`;

  if (!verifyExpectedPageExport(reportFile, reportFunctionName)) {
    options.stderr.write(
      `[vuetify-ext] ${relativeToCwd(options.cwd, reportFile)} is missing the expected export ${reportFunctionName}.\n` +
        'Create the report first or export the standard factory name before adding form steps.\n',
    );
    return 1;
  }

  if (!verifyExpectedPageExport(path.join(pageDir, `form${ext}`), baseFormFunctionName)) {
    options.stderr.write(
      `[vuetify-ext] ${relativeToCwd(options.cwd, path.join(pageDir, `form${ext}`))} is missing the expected export ${baseFormFunctionName}.\n` +
        'The base form must use the standard factory name before adding more forms.\n',
    );
    return 1;
  }

  const reportSource = fs.readFileSync(reportFile, 'utf8');
  const currentForms = extractReportFormsCount(reportSource) || 1;
  if (answers.step <= 1) {
    options.stderr.write('[vuetify-ext] create form is intended for additional report steps. Use a step number of 2 or greater.\n');
    return 1;
  }
  if (answers.step > currentForms + 1) {
    options.stderr.write(
      `[vuetify-ext] The next available step is ${currentForms + 1}, but you requested step ${answers.step}.\n` +
        'Create intermediate steps first so the report flow stays contiguous.\n',
    );
    return 1;
  }

  if (!options.force && fileExists(formFile)) {
    options.stderr.write(
      `[vuetify-ext] ${relativeToCwd(options.cwd, formFile)} already exists.\n` +
        'Use --force to overwrite it.\n',
    );
    return 1;
  }

  const normalizedReportSource = ensureReportFormMarkers(reportSource, pascalName);
  const patchedReportSource = normalizedReportSource
    ? patchReportForNewForm(normalizedReportSource, {
        pascalName,
        step: answers.step,
        nextFormsCount: Math.max(currentForms, answers.step),
      })
    : patchLegacySingleFormReport(reportSource, {
        pascalName,
        step: answers.step,
        nextFormsCount: Math.max(currentForms, answers.step),
      });
  if (!patchedReportSource) {
    options.stderr.write(
      `[vuetify-ext] Could not patch ${relativeToCwd(options.cwd, reportFile)} automatically.\n` +
        'Make sure the report uses the standard create<PageName>Report scaffold shape.\n',
    );
    return 1;
  }

  const nextIndexSource = appendExportLine(
    fileExists(indexFile) ? fs.readFileSync(indexFile, 'utf8') : `${GENERATED_MARKER} page index\n`,
    `export { ${formFunctionName} } from './${formImportStemForStep(answers.step)}';`,
  );

  const formSource = buildAdditionalFormFileSource(ext, {
    title: answers.title,
    mode: 'display',
    forms: answers.step,
    name: answers.page,
    objectType: answers.page,
  }, pascalName, answers.step);

  if (options.dryRun) {
    options.stdout.write('[vuetify-ext] Dry run only. The following files would be written or updated:\n');
    options.stdout.write(`- ${relativeToCwd(options.cwd, formFile)}\n`);
    options.stdout.write(`- ${relativeToCwd(options.cwd, reportFile)}\n`);
    options.stdout.write(`- ${relativeToCwd(options.cwd, indexFile)}\n`);
    return 0;
  }

  fs.mkdirSync(pageDir, { recursive: true });
  fs.writeFileSync(formFile, formSource, 'utf8');
  fs.writeFileSync(reportFile, patchedReportSource, 'utf8');
  fs.writeFileSync(indexFile, nextIndexSource, 'utf8');

  writeSuccess(options, 'Form step added successfully', [
    formFile,
    reportFile,
    indexFile,
  ]);
  options.stdout.write(
    '\nNext steps:\n' +
      `1. Review ${relativeToCwd(options.cwd, formFile)} and replace the starter fields with the fields for step ${answers.step}.\n` +
      `2. Review ${relativeToCwd(options.cwd, reportFile)} and confirm the inserted report step order.\n` +
      '3. Run the app and verify Prev/Next navigation now includes the new form step.\n',
  );

  return 0;
}

