import fs from 'node:fs';
import path from 'node:path';
import * as readline from 'node:readline';

export interface CreateCommandOptions {
  cwd: string;
  force: boolean;
  dryRun: boolean;
  interactive: boolean;
  stdin: NodeJS.ReadableStream;
  stdout: Pick<typeof process.stdout, 'write'>;
  stderr: Pick<typeof process.stderr, 'write'>;
  values?: Record<string, string>;
  positionals?: string[];
}

type ScriptExt = '.ts' | '.js';
type ReportMode = 'create' | 'edit' | 'display';
type MenuItemTarget = 'report' | 'trigger' | 'collection' | 'dashboard';
type PrepareWritesResult = 'ok' | 'dry-run' | 'error';

interface PageAnswers {
  name: string;
  title: string;
  objectType: string;
  mode: ReportMode;
}

interface ReportAnswers extends PageAnswers {
  forms: number;
}

interface TriggerAnswers extends PageAnswers {
  idField: string;
  multiple: boolean;
}

interface CollectionAnswers extends TriggerAnswers {
  withReport: boolean;
  withTrigger: boolean;
}

interface MenuItemAnswers {
  page: string;
  target: MenuItemTarget;
  mode: ReportMode;
  text: string;
  subText: string;
  icon: string;
  color: string;
  menuFile?: string;
}

interface SubMenuAnswers {
  name: string;
  title: string;
  text: string;
  subText: string;
  icon: string;
  color: string;
  parent?: string;
  menuFile?: string;
}

interface FormStepAnswers {
  page: string;
  step: number;
  title: string;
}

interface FileWrite {
  file: string;
  content: string;
}

const GENERATED_MARKER = '// Generated by vuetify-ext';
const MENU_IMPORT_MARKER = '// vuetify-ext:menu-imports';
const MENU_ITEM_MARKER = '// vuetify-ext:menu-items';
const REPORT_IMPORT_MARKER = '// vuetify-ext:report-form-imports';
const REPORT_RESOLVER_MARKER = '// vuetify-ext:report-form-resolver';
const FORM_PARTS_MARKER = '// vuetify-ext:form-parts';
const FORM_FIELDS_MARKER_PREFIX = '// vuetify-ext:part:';

