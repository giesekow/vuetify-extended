function listPageNames(cwd: string) {
  const pagesDir = path.join(cwd, 'src/pages');
  if (!fs.existsSync(pagesDir)) {
    return [];
  }
  return fs.readdirSync(pagesDir).filter((entry) => fs.statSync(path.join(pagesDir, entry)).isDirectory());
}

function listSourceFiles(root: string): string[] {
  if (!fs.existsSync(root)) {
    return [];
  }
  const entries = fs.readdirSync(root, { withFileTypes: true });
  const files: string[] = [];
  for (const entry of entries) {
    const fullPath = path.join(root, entry.name);
    if (entry.isDirectory()) {
      files.push(...listSourceFiles(fullPath));
      continue;
    }
    if (/\.(ts|js)$/.test(entry.name)) {
      files.push(fullPath);
    }
  }
  return files;
}

function resolveProjectScriptExtension(cwd: string): ScriptExt {
  if (findExistingFile(cwd, ['src/main.ts', 'src/menu/index.ts'])) {
    return '.ts';
  }
  return fileExists(path.join(cwd, 'tsconfig.json')) ? '.ts' : '.js';
}

function resolveExistingPageScriptExtension(cwd: string, page: string): ScriptExt | undefined {
  const tsFiles = ['report.ts', 'form.ts', 'trigger.ts', 'collection.ts', 'dashboard.ts', 'index.ts'];
  if (tsFiles.some((file) => fileExists(path.join(cwd, 'src/pages', page, file)))) {
    return '.ts';
  }
  const jsFiles = ['report.js', 'form.js', 'trigger.js', 'collection.js', 'dashboard.js', 'index.js'];
  if (jsFiles.some((file) => fileExists(path.join(cwd, 'src/pages', page, file)))) {
    return '.js';
  }
  return undefined;
}

function verifyExpectedPageExport(file: string, exportName: string) {
  if (!fileExists(file)) {
    return false;
  }
  return sourceIncludesNamedExport(fs.readFileSync(file, 'utf8'), exportName);
}

function sourceIncludesNamedExport(source: string, exportName: string) {
  const escaped = escapeRegExp(exportName);
  return [
    new RegExp(`export\\s+function\\s+${escaped}\\s*\\(`),
    new RegExp(`export\\s+(?:const|let|var)\\s+${escaped}\\s*=`),
    new RegExp(`export\\s*\\{[^}]*\\b${escaped}\\b[^}]*\\}`),
  ].some((pattern) => pattern.test(source));
}

function fileExists(file: string) {
  return fs.existsSync(file);
}

function relativeToCwd(cwd: string, file: string) {
  return path.relative(cwd, file) || '.';
}

function humanizeName(value: string) {
  return value
    .replace(/[-_]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/\b\w/g, (match) => match.toUpperCase());
}

function slugifyName(value: string) {
  return value
    .trim()
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/[^a-zA-Z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .toLowerCase();
}

function toPascalCase(value: string) {
  return slugifyName(value)
    .split('-')
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');
}

function capitalize(value: string) {
  return value.charAt(0).toUpperCase() + value.slice(1);
}

function sanitizeIdentifier(value: string) {
  let identifier = toPascalCase(value);
  if (!identifier) {
    identifier = 'GeneratedValue';
  }
  if (/^[0-9]/.test(identifier)) {
    identifier = `Value${identifier}`;
  }
  return identifier.charAt(0).toLowerCase() + identifier.slice(1);
}

function serializeString(value: string) {
  return JSON.stringify(value);
}

function serializeUITextDescriptor(key: string, fallback: string) {
  return `{ key: ${serializeString(key)}, fallback: ${serializeString(fallback)} }`;
}

function pageTextKey(page: string, ...segments: string[]) {
  return ['pages', slugifyName(page), ...segments].join('.');
}

function escapeRegExp(value: string) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function normalizePositiveInt(value: string | number | undefined, fallback: number) {
  const parsed = Number(value);
  return Number.isInteger(parsed) && parsed > 0 ? parsed : fallback;
}

function parseOptionalBoolean(value: string | undefined) {
  if (value === undefined) return undefined;
  const normalized = value.trim().toLowerCase();
  if (['true', '1', 'yes', 'y'].includes(normalized)) return true;
  if (['false', '0', 'no', 'n'].includes(normalized)) return false;
  return undefined;
}

async function promptText(rl: readline.Interface, label: string, defaultValue?: string, allowEmpty: boolean = false) {
  while (true) {
    const suffix = defaultValue ? ` [${defaultValue}]` : '';
    const value = (await ask(rl, `${label}${suffix}: `)).trim();
    if (value.length > 0) return value;
    if (defaultValue !== undefined) return defaultValue;
    if (allowEmpty) return '';
  }
}

async function promptNumber(rl: readline.Interface, label: string, defaultValue: number, min: number) {
  while (true) {
    const value = (await ask(rl, `${label} [${defaultValue}]: `)).trim();
    if (!value) return defaultValue;
    const parsed = Number(value);
    if (Number.isInteger(parsed) && parsed >= min) return parsed;
  }
}

async function promptChoice(rl: readline.Interface, label: string, choices: string[], defaultValue: string) {
  while (true) {
    const value = (await ask(rl, `${label} [${defaultValue}]: `)).trim().toLowerCase();
    const resolved = value || defaultValue;
    if (choices.includes(resolved)) return resolved;
  }
}

async function promptBoolean(rl: readline.Interface, label: string, defaultValue: boolean) {
  while (true) {
    const suffix = defaultValue ? ' [Y/n]' : ' [y/N]';
    const value = (await ask(rl, `${label}${suffix}: `)).trim().toLowerCase();
    if (!value) return defaultValue;
    if (['y', 'yes', 'true', '1'].includes(value)) return true;
    if (['n', 'no', 'false', '0'].includes(value)) return false;
  }
}

function ask(rl: readline.Interface, prompt: string): Promise<string> {
  return new Promise((resolve) => {
    rl.question(prompt, (answer) => resolve(answer));
  });
}
