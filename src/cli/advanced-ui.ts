export async function runDoctorCommand(options: CreateCommandOptions): Promise<number> {
  const issues: string[] = [];
  const fixes: string[] = [];

  const pagesDir = path.join(options.cwd, 'src/pages');
  if (!fs.existsSync(pagesDir)) {
    issues.push('Missing src/pages directory.');
  }
  if (!findExistingFile(options.cwd, ['src/menu/index.ts', 'src/menu/index.js'])) {
    issues.push('Missing src/menu/index.ts or src/menu/index.js.');
  }
  if (!findExistingFile(options.cwd, ['src/bootstrap/index.ts', 'src/bootstrap/index.js'])) {
    issues.push('Missing src/bootstrap/index.ts or src/bootstrap/index.js.');
  }
  if (!findExistingFile(options.cwd, ['src/api/index.ts', 'src/api/index.js'])) {
    issues.push('Missing src/api/index.ts or src/api/index.js.');
  }

  for (const page of listPageNames(options.cwd)) {
    const ext = resolveExistingPageScriptExtension(options.cwd, page) || resolveProjectScriptExtension(options.cwd);
    const pageDir = path.join(options.cwd, 'src/pages', page);
    const reportFile = path.join(pageDir, `report${ext}`);
    const formFile = path.join(pageDir, `form${ext}`);
    const dashboardFile = path.join(pageDir, `dashboard${ext}`);
    const indexFile = path.join(pageDir, `index${ext}`);
    const pascalName = toPascalCase(page);

    if (fileExists(reportFile)) {
      if (!verifyExpectedPageExport(reportFile, `create${pascalName}Report`)) {
        issues.push(`${relativeToCwd(options.cwd, reportFile)} is missing create${pascalName}Report.`);
      }
      const source = fs.readFileSync(reportFile, 'utf8');
      if (!source.includes('// vuetify-ext:report-form-imports') || !source.includes('// vuetify-ext:report-form-resolver')) {
        fixes.push(`${relativeToCwd(options.cwd, reportFile)} can be migrated to add report form markers.`);
      }
    }

    if (fileExists(formFile)) {
      const source = fs.readFileSync(formFile, 'utf8');
      if (!source.includes(FORM_PARTS_MARKER) || !source.includes(`${FORM_FIELDS_MARKER_PREFIX}1:fields`)) {
        fixes.push(`${relativeToCwd(options.cwd, formFile)} can be migrated to add form markers.`);
      }
    }

    if (fileExists(dashboardFile)) {
      const source = fs.readFileSync(dashboardFile, 'utf8');
      if (!source.includes(DASHBOARD_MAIN_MARKER)) {
        fixes.push(`${relativeToCwd(options.cwd, dashboardFile)} can be migrated to add dashboard markers.`);
      }
    }

    if (fileExists(indexFile)) {
      const source = fs.readFileSync(indexFile, 'utf8');
      const expectedExports = [
        fileExists(formFile) ? `create${pascalName}Form` : undefined,
        fileExists(reportFile) ? `create${pascalName}Report` : undefined,
        fileExists(path.join(pageDir, `trigger${ext}`)) ? `create${pascalName}Trigger` : undefined,
        fileExists(path.join(pageDir, `collection${ext}`)) ? `create${pascalName}Collection` : undefined,
        fileExists(dashboardFile) ? `create${pascalName}Dashboard` : undefined,
      ].filter(Boolean) as string[];

      for (const exportName of expectedExports) {
        if (!sourceIncludesNamedExport(source, exportName)) {
          fixes.push(`${relativeToCwd(options.cwd, indexFile)} is missing export ${exportName}.`);
        }
      }
    }
  }

  if (issues.length === 0 && fixes.length === 0) {
    options.stdout.write('[vuetify-ext] Doctor found no issues.\n');
    return 0;
  }

  if (issues.length > 0) {
    options.stdout.write('[vuetify-ext] Structural issues:\n');
    for (const issue of issues) {
      options.stdout.write(`- ${issue}\n`);
    }
  }
  if (fixes.length > 0) {
    options.stdout.write('[vuetify-ext] Recommended migrations:\n');
    for (const fix of fixes) {
      options.stdout.write(`- ${fix}\n`);
    }
  }

  return 1;
}

export async function runMigrateCommand(options: CreateCommandOptions): Promise<number> {
  const apply = parseOptionalBoolean(options.values?.apply) === true;
  const writes: FileWrite[] = [];

  for (const sourceFile of listSourceFiles(path.join(options.cwd, 'src'))) {
    const source = fs.readFileSync(sourceFile, 'utf8');
    const next = source.replace(/AppManager\.showUI\(([^)]+)\)/g, 'AppManager.showTrigger($1)');
    if (next !== source) {
      writes.push({ file: sourceFile, content: next });
    }
  }

  for (const page of listPageNames(options.cwd)) {
    const ext = resolveExistingPageScriptExtension(options.cwd, page) || resolveProjectScriptExtension(options.cwd);
    const pageDir = path.join(options.cwd, 'src/pages', page);
    const pascalName = toPascalCase(page);
    const reportFile = path.join(pageDir, `report${ext}`);
    const formFile = path.join(pageDir, `form${ext}`);
    const dashboardFile = path.join(pageDir, `dashboard${ext}`);
    const indexFile = path.join(pageDir, `index${ext}`);

    if (fileExists(reportFile)) {
      const source = fs.readFileSync(reportFile, 'utf8');
      const next = ensureReportMarkers(source, pascalName);
      if (next && next !== source) {
        writes.push({ file: reportFile, content: next });
      }
    }

    if (fileExists(formFile)) {
      const source = fs.readFileSync(formFile, 'utf8');
      const next = ensureFormScaffoldMarkers(source);
      if (next && next !== source) {
        writes.push({ file: formFile, content: next });
      }
    }

    if (fileExists(dashboardFile)) {
      const source = fs.readFileSync(dashboardFile, 'utf8');
      const next = ensureDashboardMarkers(source);
      if (next && next !== source) {
        writes.push({ file: dashboardFile, content: next });
      }
    }

    const exports: string[] = [];
    if (fileExists(formFile)) exports.push(`export { create${pascalName}Form } from './form';`);
    if (fileExists(reportFile)) exports.push(`export { create${pascalName}Report } from './report';`);
    if (fileExists(path.join(pageDir, `trigger${ext}`))) exports.push(`export { create${pascalName}Trigger } from './trigger';`);
    if (fileExists(path.join(pageDir, `collection${ext}`))) exports.push(`export { create${pascalName}Collection } from './collection';`);
    if (fileExists(dashboardFile)) exports.push(`export { create${pascalName}Dashboard } from './dashboard';`);

    for (const fileName of fs.readdirSync(pageDir).filter((entry) => /^form-\d+\.(ts|js)$/.test(entry))) {
      const step = Number(fileName.match(/^form-(\d+)\./)?.[1] || 0);
      if (step > 1) {
        exports.push(`export { create${pascalName}Form${step} } from './form-${step}';`);
      }
    }

    const nextIndex = appendLines(fileExists(indexFile) ? fs.readFileSync(indexFile, 'utf8') : `${GENERATED_MARKER} page index\n`, exports);
    if (!fileExists(indexFile) || nextIndex !== fs.readFileSync(indexFile, 'utf8')) {
      writes.push({ file: indexFile, content: nextIndex });
    }
  }

  if (writes.length === 0) {
    options.stdout.write('[vuetify-ext] No migrations were needed.\n');
    return 0;
  }

  if (!apply || options.dryRun) {
    options.stdout.write('[vuetify-ext] The following files would be updated:\n');
    for (const write of uniqueWrites(writes)) {
      options.stdout.write(`- ${relativeToCwd(options.cwd, write.file)}\n`);
    }
    options.stdout.write('Re-run with --apply to write the changes.\n');
    return 0;
  }

  writeFiles(uniqueWrites(writes));
  writeSuccess(options, 'Migration completed successfully', uniqueWrites(writes).map((entry) => entry.file));
  return 0;
}

