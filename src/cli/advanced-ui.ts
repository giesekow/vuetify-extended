function ensureFormScaffoldMarkers(source: string): string | undefined {
  let next = source;
  const childPattern = /children:\s*\(\)\s*=>\s*\[/g;
  const matches = Array.from(next.matchAll(childPattern));
  if (!next.includes(FORM_PARTS_MARKER)) {
    if (!matches[0]?.index) {
      return undefined;
    }
    const rootInsertAt = matches[0].index + matches[0][0].length;
    next = `${next.slice(0, rootInsertAt)}\n        ${FORM_PARTS_MARKER}${next.slice(rootInsertAt)}`;
  }
  if (!next.includes(`${FORM_FIELDS_MARKER_PREFIX}1:fields`)) {
    const rematches = Array.from(next.matchAll(childPattern));
    if (!rematches[1]?.index) {
      return undefined;
    }
    const partInsertAt = rematches[1].index + rematches[1][0].length;
    next = `${next.slice(0, partInsertAt)}\n              ${FORM_FIELDS_MARKER_PREFIX}1:fields${next.slice(partInsertAt)}`;
  }
  return next;
}

function ensureDashboardMarkers(source: string): string | undefined {
  let next = source;
  if (!next.includes(DASHBOARD_IMPORT_MARKER)) {
    const importMatches = Array.from(next.matchAll(/^import .*$/gm));
    const lastImport = importMatches[importMatches.length - 1];
    if (!lastImport) {
      return undefined;
    }
    const insertAt = (lastImport.index || 0) + lastImport[0].length;
    next = `${next.slice(0, insertAt)}\n${DASHBOARD_IMPORT_MARKER}${next.slice(insertAt)}`;
  }
  const markers: Array<{ key: string; pattern: RegExp }> = [
    { key: DASHBOARD_TOP_MARKER, pattern: /topChildren:\s*\(\)\s*=>\s*\[/ },
    { key: DASHBOARD_MAIN_MARKER, pattern: /children:\s*\(\)\s*=>\s*\[/ },
    { key: DASHBOARD_BOTTOM_MARKER, pattern: /bottomChildren:\s*\(\)\s*=>\s*\[/ },
  ];
  for (const marker of markers) {
    if (next.includes(marker.key)) {
      continue;
    }
    if (!marker.pattern.test(next)) {
      return undefined;
    }
    next = next.replace(marker.pattern, (match) => `${match}\n        ${marker.key}`);
  }
  return next;
}

function ensureReportMarkers(source: string, pascalName: string): string | undefined {
  if (source.includes('// vuetify-ext:report-form-imports') && source.includes('// vuetify-ext:report-form-resolver')) {
    return source;
  }
  let next = source;
  const baseImportPattern = new RegExp(`import\\s*\\{\\s*create${pascalName}Form\\s*\\}\\s*from\\s*['"]\\.\\/form['"];?`);
  const baseImportMatch = next.match(baseImportPattern);
  if (!baseImportMatch) {
    return undefined;
  }
  if (!next.includes('// vuetify-ext:report-form-imports')) {
    next = next.replace(baseImportMatch[0], `${baseImportMatch[0]}\n// vuetify-ext:report-form-imports`);
  }
  if (!next.includes('// vuetify-ext:report-form-resolver')) {
    const usesMode = next.includes(`create${pascalName}Form(mode)`);
    const resolverCall = usesMode ? `create${pascalName}Form(mode)` : `create${pascalName}Form()`;
    const resolverReplacement = `form: async (_props, _context, index) => {\n        // vuetify-ext:report-form-resolver\n        if (index === 0) return ${resolverCall};\n        return undefined;\n      },`;
    next = next.replace(
      new RegExp(`form:\\s*async\\s*\\([^)]*\\)\\s*=>\\s*create${pascalName}Form\\((?:mode)?\\)\\s*,?`),
      resolverReplacement,
    );
  }
  return next;
}

function extractFormPartIndices(source: string) {
  return Array.from(source.matchAll(/\/\/ vuetify-ext:part:(\d+):fields/g)).map((match) => Number(match[1]));
}

