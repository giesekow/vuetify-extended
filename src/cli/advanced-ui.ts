export async function runCreateDashboardCommand(options: CreateCommandOptions): Promise<number> {
  const ext = resolveProjectScriptExtension(options.cwd);
  const answers = await resolveDashboardAnswers(options);
  if (!answers) {
    return 1;
  }

  const pageDir = path.join(options.cwd, 'src/pages', answers.name);
  const pascalName = toPascalCase(answers.name);
  const writes: FileWrite[] = [
    {
      file: path.join(pageDir, `dashboard${ext}`),
      content: buildDashboardFileSource(ext, answers, pascalName),
    },
  ];

  const prepare = prepareWrites(options, writes);
  if (prepare === 'error') {
    return 1;
  }
  if (prepare === 'dry-run') {
    options.stdout.write(`- ${relativeToCwd(options.cwd, path.join(pageDir, `index${ext}`))}\n`);
    return 0;
  }

  writeFiles(writes);
  ensureIndexExports(pageDir, ext, [`export { create${pascalName}Dashboard } from './dashboard';`]);

  if (answers.withMenuItem) {
    const menuStatus = await runCreateMenuItemCommand(withValues(options, {
      page: answers.name,
      target: 'dashboard',
      mode: 'display',
      text: answers.title,
      'sub-text': `Open the ${answers.title} dashboard.`,
      icon: 'mdi-view-dashboard-outline',
      color: 'primary',
    }));
    if (menuStatus !== 0) {
      return menuStatus;
    }
  }

  writeSuccess(options, 'Dashboard scaffolding created successfully', [
    ...writes.map((entry) => entry.file),
    path.join(pageDir, `index${ext}`),
  ]);
  return 0;
}

export async function runCreatePageCommand(options: CreateCommandOptions): Promise<number> {
  const answers = await resolvePageAnswers(options);
  if (!answers) {
    return 1;
  }

  if (answers.type === 'dashboard') {
    return runCreateDashboardCommand(withValues(options, {
      name: answers.name,
      title: answers.title,
      theme: answers.theme || 'dark',
      'with-menu-item': String(answers.withMenuItem),
    }));
  }

  if (answers.type === 'report') {
    const status = await runCreateReportCommand(withValues(options, {
      name: answers.name,
      title: answers.title,
      'object-type': answers.objectType || answers.name,
      mode: answers.mode || 'display',
      forms: String(answers.forms || 1),
    }));
    if (status !== 0 || !answers.withMenuItem) {
      return status;
    }
    return runCreateMenuItemCommand(withValues(options, {
      page: answers.name,
      target: 'report',
      mode: answers.mode || 'display',
      text: answers.title,
    }));
  }

  if (answers.type === 'trigger') {
    const status = await runCreateTriggerCommand(withValues(options, {
      name: answers.name,
      title: answers.title,
      'object-type': answers.objectType || answers.name,
      'id-field': answers.idField || '_id',
      mode: answers.mode || 'edit',
      multiple: String(answers.multiple === true),
    }));
    if (status !== 0 || !answers.withMenuItem) {
      return status;
    }
    return runCreateMenuItemCommand(withValues(options, {
      page: answers.name,
      target: 'trigger',
      mode: answers.mode || 'edit',
      text: answers.title,
    }));
  }

  const status = await runCreateCollectionCommand(withValues(options, {
    name: answers.name,
    title: answers.title,
    'object-type': answers.objectType || answers.name,
    'id-field': answers.idField || '_id',
    mode: answers.mode || 'edit',
    multiple: String(answers.multiple === true),
    'with-report': String(answers.withReport !== false),
    'with-trigger': String(answers.withTrigger !== false),
  }));
  if (status !== 0 || !answers.withMenuItem) {
    return status;
  }
  return runCreateMenuItemCommand(withValues(options, {
    page: answers.name,
    target: 'collection',
    mode: answers.mode || 'edit',
    text: answers.title,
  }));
}

export async function runCreateFieldCommand(options: CreateCommandOptions): Promise<number> {
  const answers = await resolveFieldAnswers(options);
  if (!answers) {
    return 1;
  }

  const ext = resolveExistingPageScriptExtension(options.cwd, answers.page) || resolveProjectScriptExtension(options.cwd);
  const formFile = resolveFormFile(options.cwd, answers.page, answers.step, ext);
  if (!fileExists(formFile)) {
    options.stderr.write(`[vuetify-ext] Form file not found: ${relativeToCwd(options.cwd, formFile)}\n`);
    return 1;
  }

  const fieldMarker = `// vuetify-ext:field:${answers.storage}`;
  let source = fs.readFileSync(formFile, 'utf8');
  if (source.includes(fieldMarker)) {
    writeSuccess(options, 'Field already present', [formFile]);
    return 0;
  }

  source = ensureFormScaffoldMarkers(source) || source;
  const partMarker = `${FORM_FIELDS_MARKER_PREFIX}${answers.part}:fields`;
  if (!source.includes(partMarker)) {
    options.stderr.write(
      `[vuetify-ext] Could not find part ${answers.part} in ${relativeToCwd(options.cwd, formFile)}.\n` +
        'Create the part first or run "vuetify-ext migrate --apply" to normalize scaffold markers.\n',
    );
    return 1;
  }

  const fieldBlock = buildFieldBlock(answers, fieldMarker);
  const next = source.replace(partMarker, `${partMarker}\n              ${fieldMarker}\n${fieldBlock}`);

  if (options.dryRun) {
    options.stdout.write(`[vuetify-ext] Dry run only. The following file would be updated:\n- ${relativeToCwd(options.cwd, formFile)}\n`);
    return 0;
  }

  fs.writeFileSync(formFile, next, 'utf8');
  writeSuccess(options, 'Field added successfully', [formFile]);
  return 0;
}

