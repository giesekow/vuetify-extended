function prepareWrites(options: CreateCommandOptions, writes: FileWrite[]): 'ok' | 'dry-run' | 'error' {
  const existing = writes.filter((entry) => !options.force && fileExists(entry.file));
  if (existing.length > 0) {
    options.stderr.write(
      `[vuetify-ext] The following files already exist:\n- ${existing.map((entry) => relativeToCwd(options.cwd, entry.file)).join('\n- ')}\nUse --force to overwrite them.\n`,
    );
    return 'error';
  }
  if (options.dryRun) {
    options.stdout.write('[vuetify-ext] Dry run only. The following files would be written:\n');
    for (const write of writes) {
      options.stdout.write(`- ${relativeToCwd(options.cwd, write.file)}\n`);
    }
    return 'dry-run';
  }
  return 'ok';
}

function writeFiles(writes: FileWrite[]) {
  for (const write of uniqueWrites(writes)) {
    fs.mkdirSync(path.dirname(write.file), { recursive: true });
    fs.writeFileSync(write.file, write.content, 'utf8');
  }
}

function uniqueWrites(writes: FileWrite[]) {
  const seen = new Set<string>();
  return writes.filter((write) => {
    if (seen.has(write.file)) {
      return false;
    }
    seen.add(write.file);
    return true;
  });
}

function ensureIndexExports(pageDir: string, ext: ScriptExt, exportLines: string[]) {
  const file = path.join(pageDir, `index${ext}`);
  ensureSimpleExport(file, exportLines);
}

function ensureSimpleExport(file: string, exportLineOrLines: string | string[]) {
  const lines = Array.isArray(exportLineOrLines) ? exportLineOrLines : [exportLineOrLines];
  const next = appendLines(fileExists(file) ? fs.readFileSync(file, 'utf8') : `${GENERATED_MARKER} page index\n`, lines);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, next, 'utf8');
}

function appendLines(source: string, linesToAdd: string[]) {
  const lines = source.trimEnd().split('\n').filter(Boolean);
  for (const line of linesToAdd) {
    if (!lines.includes(line)) {
      lines.push(line);
    }
  }
  return `${lines.join('\n')}\n`;
}

