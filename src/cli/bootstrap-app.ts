function buildHomePageFileSource(ext: '.ts' | '.js'): string {
  const typeImport = ext === '.ts' ? ', type NavigationEntry, type ReportMode' : '';
  const modeArg = ext === '.ts' ? `mode: ReportMode = 'display'` : `mode = 'display'`;
  const entryArg = ext === '.ts' ? 'entry?: NavigationEntry' : 'entry';
  const resolvedModeLine = ext === '.ts'
    ? `    const resolvedMode = (entry?.mode as ReportMode | undefined) || mode;`
    : `    const resolvedMode = (entry && entry.mode) || mode;`;

  return `${GENERATED_MARKER}
import { $RP${typeImport} } from 'vuetify-extended';
import { createHomeForm } from './form';

export function createHomeReport(${modeArg}) {
  return (${entryArg}) => {
${resolvedModeLine}
    return $RP(
      {
        title: ${serializeUITextDescriptor('pages.home.report.title', 'Home')},
        forms: 1,
        mode: resolvedMode,
        horizontalAlign: 'center',
        verticalAlign: 'start',
        fluid: true,
      },
      {
        form: async () => createHomeForm(),
      },
    );
  };
}
`;
}

function buildMainFileSource(options: {
  preservedImports: string[];
  prelude: string;
  useCalls: string[];
  mountSelector: string;
}): string {
  const sections: string[] = [];

  sections.push(
    `${GENERATED_MARKER}
import { createApp, defineComponent, h } from 'vue';
import { createVuetify } from 'vuetify';
import * as components from 'vuetify/components';
import * as directives from 'vuetify/directives';
import '@mdi/font/css/materialdesignicons.css';
import 'vuetify/styles';
import 'vuetify-extended/lib/esm/css/index.css';
import { initializeBootstrap } from './bootstrap';`,
  );

  if (options.preservedImports.length > 0) {
    sections.push(options.preservedImports.join('\n'));
  }

  sections.push(`const vuetify = createVuetify({
  components,
  directives,
});

const bootstrap = initializeBootstrap();`);

  if (options.prelude) {
    sections.push(options.prelude);
  }

  sections.push(`const Root = defineComponent({
  name: 'VuetifyExtendedHostApp',
  setup() {
    return () => [
      h(bootstrap.component),
      h(bootstrap.dialogs),
      h(bootstrap.notifications),
    ];
  },
});

const app = createApp(Root);
app.use(vuetify);
app.use(bootstrap.plugin);`);

  if (options.useCalls.length > 0) {
    sections.push(options.useCalls.map(useCall => `app.use(${useCall});`).join('\n'));
  }

  sections.push(`app.mount(${options.mountSelector});
bootstrap.validate({ warn: true, requireApi: false });`);

  return sections.filter(Boolean).join('\n\n') + '\n';
}

function dedupe(values: string[]): string[] {
  return Array.from(new Set(values));
}

function collectMatches(source: string, expression: RegExp): RegExpExecArray[] {
  const flags = expression.flags.includes('g') ? expression.flags : `${expression.flags}g`;
  const matcher = new RegExp(expression.source, flags);
  const matches: RegExpExecArray[] = [];
  let match = matcher.exec(source);

  while (match) {
    matches.push(match);
    match = matcher.exec(source);
  }

  return matches;
}

function serializeString(value: string | undefined): string {
  return JSON.stringify(value || '');
}

function serializeUITextDescriptor(key: string, fallback: string): string {
  return `{ key: ${serializeString(key)}, fallback: ${serializeString(fallback)} }`;
}

function defaultSocketURL(apiURL: string): string {
  return `${apiURL.replace(/\/+$/, '')}/realtime`;
}

function fileExists(file: string): boolean {
  return fs.existsSync(file);
}

function relativeToCwd(cwd: string, absolutePath: string): string {
  return path.relative(cwd, absolutePath) || path.basename(absolutePath);
}

function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}
